import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = `
  import { createDefaultOptimisationOptions } from "./src/model/defaultOptimisationPresets.ts";
  import { optimisePortfolioWithOutcome } from "./src/model/optimiser.ts";
  import { OPTIMISER_STATE_MODEL_VERSION } from "./src/model/optimisationState.ts";
  import { createObjectiveAnalysis } from "./src/model/objectiveAnalysis.ts";
  import { createProductRoutingDecision } from "./src/model/productRoutingDecision.ts";

  const objectivesByMode = {
    base: ["bullish", "bearish", "spotParity", "benchmarkDominance"],
    lending: ["bullish", "bearish", "spotParity", "debtParity", "benchmarkDominance"],
    perp: ["bullish", "bearish", "spotParity", "perpParity", "benchmarkDominance"],
  };

  export const generated = {
    modelVersion: OPTIMISER_STATE_MODEL_VERSION,
    presets: Object.entries(objectivesByMode).flatMap(([comparisonMode, objectives]) =>
      objectives.map((objective) => {
        const options = createDefaultOptimisationOptions(comparisonMode, objective);
        const outcome = optimisePortfolioWithOutcome(options);
        if (outcome.diagnostics) outcome.diagnostics.durationMs = 0;
        if (!outcome.config) throw new Error("Default optimisation failed: " + comparisonMode + ":" + objective);
        return {
          comparisonMode,
          objective,
          outcome,
          productRoutingDecision: createProductRoutingDecision(options, outcome),
          objectiveAnalysis: createObjectiveAnalysis({
            objective,
            config: outcome.config,
            spotParityPercent: options.spotParityPercent,
            debtParityPercent: options.debtParityPercent,
            perpParityPercent: options.perpParityPercent,
            debtPosition: options.debtPosition,
            perpPosition: options.perpPosition,
            bearishTargetPercent: options.bearishTargetPercent ?? -75,
            analysisRange: options.analysisRange,
            comparisonMode,
          }),
        };
      }),
    ),
  };
`;

const bundle = await build({
  absWorkingDir: root,
  stdin: { contents: entry, resolveDir: root, sourcefile: "generate-presets.ts" },
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  write: false,
});
const moduleUrl = `data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString("base64")}`;
const { generated } = await import(moduleUrl);
const output = `// Generated by npm run generate:presets. Do not edit by hand.\n` +
  `import type { DefaultOptimisationPreset } from "./defaultOptimisationPresets";\n\n` +
  `export const GENERATED_DEFAULT_OPTIMISATION_PRESET_MODEL_VERSION = ${JSON.stringify(generated.modelVersion)};\n` +
  `export const GENERATED_DEFAULT_OPTIMISATION_PRESETS: DefaultOptimisationPreset[] = ${JSON.stringify(
    generated.presets,
    (key, value) => key === "durationMs" ? 0 : value,
    2,
  )};\n`;

await writeFile(path.join(root, "src/model/generatedDefaultOptimisationPresets.ts"), output);
console.log(`Generated ${generated.presets.length} optimiser presets for ${generated.modelVersion}.`);
